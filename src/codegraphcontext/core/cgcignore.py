from pathlib import Path
from typing import Iterable, Optional, Tuple
import re
from ..utils.debug_log import warning_logger


def _resolve_explicit_path(ignore_root: Path, explicit_path: Optional[str]) -> Optional[Path]:
    """Resolve an explicit .cgcignore path relative to *ignore_root*."""
    if not explicit_path:
        return None

    candidate = Path(explicit_path)
    if not candidate.is_absolute():
        candidate = (ignore_root / candidate).resolve()
    return candidate

def parse_cgcignore_lines(lines: Iterable[str]) -> list[str]:
    """Return valid ignore patterns from raw .cgcignore lines.

    Valid patterns are non-empty lines that do not start with '#'.
    """
    patterns: list[str] = []
    for raw_line in lines:
        line = raw_line.strip()
        if not line or line.startswith("#"):
            continue
        patterns.append(line)
    return patterns


def _split_generated_patterns(
    lines: Iterable[str], generated_defaults: list[str]
) -> Tuple[list[str], list[str]]:
    """Separate recognized generated defaults from later user rules."""
    defaults_left = list(generated_defaults)
    generated: list[str] = []
    user_patterns: list[str] = []
    for pattern in parse_cgcignore_lines(lines):
        try:
            defaults_left.remove(pattern)
        except ValueError:
            user_patterns.append(pattern)
        else:
            generated.append(pattern)
    return generated, user_patterns


def find_cgcignore(ignore_root: Path, explicit_path: Optional[str] = None) -> Optional[Path]:
    """Find a repository-local .cgcignore, with explicit path fallback."""

    # Search parent folders only within the current git worktree. If the
    # indexed path is outside a git repo (e.g. /tmp test dirs), avoid crawling
    # up to filesystem-wide locations like /tmp/.cgcignore.
    git_root: Optional[Path] = None
    probe = ignore_root
    while True:
        if (probe / ".git").exists():
            git_root = probe
            break
        if probe.parent == probe:
            break
        probe = probe.parent

    curr = ignore_root
    while True:
        candidate = curr / ".cgcignore"
        if candidate.exists():
            return candidate

        if git_root is None:
            return None

        if curr == git_root:
            break

        curr = curr.parent

    explicit_candidate = _resolve_explicit_path(ignore_root, explicit_path)
    if explicit_candidate and explicit_candidate.exists():
        return explicit_candidate
    return None

def find_gitignore(ignore_root: Path) -> Optional[Path]:
    """Find a repository-local .gitignore, searched the same way as .cgcignore.

    Bounded to the git worktree for the same reason find_cgcignore is: an indexed
    path outside a repo must not pick up something like /tmp/.gitignore.
    """
    git_root: Optional[Path] = None
    probe = ignore_root
    while True:
        if (probe / ".git").exists():
            git_root = probe
            break
        if probe.parent == probe:
            break
        probe = probe.parent

    curr = ignore_root
    while True:
        candidate = curr / ".gitignore"
        if candidate.is_file():
            return candidate
        if git_root is None or curr == git_root:
            return None
        curr = curr.parent


def ensure_default_cgcignore(path: Path, default_patterns: list[str]) -> None:
    """Create a .cgcignore file with default patterns when it does not exist."""
    path.parent.mkdir(parents=True, exist_ok=True)
    content = "# Auto-generated by CodeGraphContext\n"
    content += "# Default ignore patterns for binary/media files\n"
    content += "# Add your own patterns below\n\n"
    content += "\n".join(default_patterns) + "\n"
    path.write_text(content, encoding="utf-8")


def _read_user_cgcignore_patterns(path: Path, generated_defaults: list[str]) -> list[str]:
    """Read user rules while keeping an auto-generated defaults block in the default layer."""
    lines = path.read_text(encoding="utf-8").splitlines()
    patterns = parse_cgcignore_lines(lines)
    if not lines or lines[0].strip() != "# Auto-generated by CodeGraphContext":
        return patterns

    defaults_left = list(generated_defaults)
    user_patterns = []
    for pattern in patterns:
        try:
            defaults_left.remove(pattern)
        except ValueError:
            user_patterns.append(pattern)
    return user_patterns


def read_cgcignore_patterns(path: Path, default_patterns: list[str]) -> list[str]:
    """Read .cgcignore patterns and merge them with defaults.

    Empty lines and comment lines are ignored.
    """
    if not path.exists():
        return list(default_patterns)

    user_patterns = _read_user_cgcignore_patterns(path, default_patterns)
    # Defaults first, user patterns last: matching is last-match-wins, so the
    # trailing list is the one that takes precedence.
    return list(default_patterns) + user_patterns

class CGCIgnoreMatcher:
    def __init__(
        self,
        patterns: list[str],
        root_dir: Path,
        sources: Optional[list[str]] = None,
    ):
        self.root_dir = root_dir
        self.rules = self._compile_patterns(patterns, sources)
        
    def _translate_segment(self, seg: str) -> str:
        """Translates a single gitwildmatch segment into regex, completely avoiding fnmatch."""
        i, n = 0, len(seg)
        res = ""
        while i < n:
            c = seg[i]
            i += 1
            if c == '*':
                res += '[^/]*'
            elif c == '?':
                res += '[^/]'
            elif c == '\\':
                # Handle gitignore escape sequence (e.g. \! matches a literal !)
                if i < n:
                    res += re.escape(seg[i])
                    i += 1
                else:
                    res += re.escape('\\')
            elif c == '[':
                j = i
                if j < n and seg[j] == '!':
                    j += 1
                if j < n and seg[j] == ']':
                    j += 1
                while j < n and seg[j] != ']':
                    j += 1
                if j >= n:
                    res += '\\['
                else:
                    stuff = seg[i:j].replace('\\', '\\\\')
                    i = j + 1
                    if stuff[0] == '!':
                        stuff = '^' + stuff[1:]
                    elif stuff[0] == '^':
                        stuff = '\\' + stuff
                    res += '[' + stuff + ']'
            else:
                res += re.escape(c)
        return res

    def _compile_patterns(
        self,
        patterns: list[str],
        sources: Optional[list[str]] = None,
    ) -> list[Tuple[bool, re.Pattern, str, Optional[str]]]:
        rules = []
        for index, raw_pat in enumerate(patterns):
            source = sources[index] if sources and index < len(sources) else None
            pat = raw_pat.strip()
            if not pat or pat.startswith('#'):
                continue
            
            is_negation = pat.startswith('!')
            if is_negation:
                pat = pat[1:]
                
            is_dir_only = pat.endswith('/')
            if is_dir_only:
                pat = pat[:-1]

            is_root_anchored = pat.startswith('/')
            if is_root_anchored:
                pat = pat[1:]

            # Under gitignore semantics a slash anywhere except the trailing
            # position anchors the pattern to the ignore root: `src/generated`
            # matches <root>/src/generated only, never vendor/src/generated.
            # Only a *leading* slash used to anchor here, so any multi-segment
            # pattern matched at every depth and silently over-ignored.
            # `build/` keeps matching at any depth -- its slash was already
            # stripped as is_dir_only, so no internal slash remains.
            if '/' in pat:
                is_root_anchored = True

            # `**` spans whole path segments, never part of one. Joining the
            # translated pieces with a bare `.*` lets the wildcard match inside a
            # segment, so `docs/**` would swallow `docstring.py` and `**/build`
            # would swallow `rebuild/`. Join with a separator-aware bridge instead.
            raw_segments = pat.split('**')
            segments = [seg.strip('/') for seg in raw_segments]
            translated_segments = [self._translate_segment(seg) if seg else ''
                                   for seg in segments]

            parts = [translated_segments[0]]
            for left, right in zip(translated_segments, translated_segments[1:]):
                if not left:
                    # leading `**/` — match any number of leading segments
                    parts.append(r'(?:.*/)?' if right else '.*')
                elif not right:
                    # trailing `/**` — must have at least one child segment
                    parts.append('/.*')
                else:
                    # `a/**/b` — zero or more whole segments between the two
                    parts.append(r'/(?:.*/)?')
                parts.append(right)
            regex_str = ''.join(parts)
            
            if is_root_anchored:
                regex_str = r'\A' + regex_str
            else:
                # Anchor to a path-segment boundary so a directory pattern like
                # `out/` matches the segment `out`, not the substring inside
                # `layout/` / `checkout/` (match_file applies the regex via re.search).
                regex_str = r'(?:\A|.*/)' + regex_str
                
            if is_dir_only:
                # Must match a directory (so it must have trailing slash, or children)
                regex_str = regex_str + r'(?:/.*)\Z'
            else:
                regex_str = regex_str + r'(?:/.*)?\Z'
                
            try:
                compiled = re.compile(regex_str, re.DOTALL)
                rules.append((is_negation, compiled, raw_pat, source))
            except re.error as e:
                warning_logger(f"Failed to compile .cgcignore pattern '{raw_pat}': {e}")
                continue
                
        return rules
        
    def _matching_ignore_rule(self, file_path) -> Optional[Tuple[str, Optional[str]]]:
        try:
            if isinstance(file_path, Path) and file_path.is_absolute():
                rel_path = str(file_path.relative_to(self.root_dir)).replace("\\", "/")
            else:
                rel_path = str(file_path).replace("\\", "/")
        except ValueError:
            # If not relative to root, just use absolute
            rel_path = str(file_path).replace("\\", "/")
            
        rel_path = rel_path.lstrip('/')
        
        ignored_rule: Optional[Tuple[str, Optional[str]]] = None
        for is_neg, rule, raw_pattern, source in self.rules:
            if rule.search(rel_path):
                ignored_rule = None if is_neg else (raw_pattern, source)
        return ignored_rule

    def match_reason(self, file_path) -> Optional[str]:
        """Return the winning ignore rule when *file_path* is excluded.

        Directory-only patterns require a trailing slash in the path string.
        Callers that check a directory should append it before matching.
        """
        ignored_rule = self._matching_ignore_rule(file_path)
        if ignored_rule is None:
            return None
        raw_pattern, source = ignored_rule
        label = f"{source} pattern" if source else "ignore rule"
        return f"ignored by {label} '{raw_pattern}'"

    def match_file(self, file_path) -> bool:
        """Return whether *file_path* is excluded by the configured patterns."""
        return self._matching_ignore_rule(file_path) is not None

def build_ignore_spec(
    ignore_root: Path,
    default_patterns: list[str],
    explicit_path: Optional[str] = None,
    create_default_cgcignore: bool = True,
    missing_explicit_defaults: Optional[list[str]] = None,
    raise_on_gitignore_error: bool = False,
    raise_on_cgcignore_error: bool = True,
) -> Tuple[CGCIgnoreMatcher, Optional[Path]]:
    """Build CGCIgnoreMatcher using defaults, .gitignore, and user .cgcignore rules.

    ``missing_explicit_defaults`` supplies configured defaults in memory when
    an explicit ignore file has not been created yet. When that file is a
    generated global ignore file, its present defaults are also kept ahead of
    ``.gitignore`` while appended user rules remain after it.

    Returns the compiled spec and the discovered/created .cgcignore path.
    """
    local_cgcignore_path = find_cgcignore(ignore_root, explicit_path=None)
    explicit_cgcignore_path = _resolve_explicit_path(ignore_root, explicit_path)
    configured_defaults: list[str] = []
    if (
        explicit_cgcignore_path
        and not explicit_cgcignore_path.exists()
        and missing_explicit_defaults
    ):
        configured_defaults = list(missing_explicit_defaults)

    if local_cgcignore_path is None:
        local_cgcignore_path = ignore_root / ".cgcignore"
        if create_default_cgcignore:
            ensure_default_cgcignore(local_cgcignore_path, default_patterns)

    merged_user_patterns: list[str] = []
    merged_user_sources: list[str] = []
    if local_cgcignore_path.is_file():
        try:
            local_patterns = _read_user_cgcignore_patterns(local_cgcignore_path, default_patterns)
        except (OSError, UnicodeError) as e:
            if raise_on_cgcignore_error:
                raise
            warning_logger(f"Failed to read {local_cgcignore_path}: {e}")
            local_patterns = []
        merged_user_patterns.extend(local_patterns)
        merged_user_sources.extend([".cgcignore"] * len(local_patterns))

    if explicit_cgcignore_path and explicit_cgcignore_path.exists() and explicit_cgcignore_path != local_cgcignore_path:
        try:
            explicit_lines = explicit_cgcignore_path.read_text(encoding="utf-8").splitlines()
        except (OSError, UnicodeError) as e:
            if raise_on_cgcignore_error:
                raise
            warning_logger(f"Failed to read {explicit_cgcignore_path}: {e}")
            explicit_lines = []
        explicit_patterns = parse_cgcignore_lines(explicit_lines)
        if (
            explicit_lines
            and explicit_lines[0].strip() == "# Default .cgcignore patterns"
            and missing_explicit_defaults
        ):
            configured_defaults, explicit_patterns = _split_generated_patterns(
                explicit_lines, missing_explicit_defaults
            )
        merged_user_patterns.extend(explicit_patterns)
        merged_user_sources.extend([".cgcignore"] * len(explicit_patterns))

    gitignore_patterns: list[str] = []
    gitignore_path = find_gitignore(ignore_root)
    if gitignore_path is not None:
        try:
            gitignore_patterns = parse_cgcignore_lines(gitignore_path.read_text(encoding="utf-8").splitlines())
        except (OSError, UnicodeError) as e:
            if raise_on_gitignore_error:
                raise
            warning_logger(f"Failed to read {gitignore_path}: {e}")

    # Defaults first, user patterns last: matching is last-match-wins (see
    # CGCIgnoreMatcher.match_file), so defaults must not override user negations.
    # The in-memory defaults for a missing configured file are also defaults,
    # so .gitignore negations must be allowed to re-include those paths.
    # .cgcignore sits after .gitignore so it can still bring a git-ignored path
    # back into the graph.
    all_patterns = (
        list(default_patterns)
        + configured_defaults
        + gitignore_patterns
        + merged_user_patterns
    )
    pattern_sources = (
        ["built-in default"] * len(default_patterns)
        + ([".cgcignore"] * len(configured_defaults))
        + ([".gitignore"] * len(gitignore_patterns))
        + merged_user_sources
    )
    resolved_cgcignore = local_cgcignore_path if local_cgcignore_path.is_file() else None
    return CGCIgnoreMatcher(all_patterns, ignore_root, pattern_sources), resolved_cgcignore
